#!/usr/bin/env python3
"""isayscribe v3.4 — Replace Text with correct WFTextTokenString format."""
import plistlib, uuid, json, os, subprocess

BASE = "/Users/clementsemerson/isayscribe"

with open(os.path.join(BASE, "prompt.txt"), "r", encoding="utf-8") as f:
    SYSTEM_PROMPT = f.read()

def uid():
    return str(uuid.uuid4()).upper()

U_CMT1 = uid(); U_CMT2 = uid()
U_KEY  = uid()   # Text: API key
U_DICT = uid()   # Dictate Text
U_JSON = uid()   # Text: JSON body with __T__ placeholder
U_RPL  = uid()   # Replace Text
U_DL   = uid()   # Download URL
U_GET  = uid()   # getvalueforkey
U_NOTE = uid()   # Create Note

# Build JSON template with a short unique placeholder
JSON_BODY = json.dumps({
    "model": "llama-3.3-70b-versatile",
    "messages": [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": "__T__"},
    ]
}, ensure_ascii=False)

def tts_attach(out_uuid, out_name):
    """WFTextTokenString with single placeholder at position 0."""
    return {
        "Value": {
            "attachmentsByRange": {
                "{0, 1}": {"OutputUUID": out_uuid, "OutputName": out_name, "Type": "ActionOutput"}
            },
            "string": "\ufffc",  # U+FFFC placeholder
        },
        "WFSerializationType": "WFTextTokenString",
    }

def tta_attach(out_uuid, out_name):
    """WFTextTokenAttachment."""
    return {
        "Value": {"OutputUUID": out_uuid, "OutputName": out_name, "Type": "ActionOutput"},
        "WFSerializationType": "WFTextTokenAttachment",
    }

def wf_kv(key, val):
    return {
        "UUID": uid(), "WFKey": {"Value": {"string": key}, "WFSerializationType": "WFTextTokenString"},
        "WFItemType": 0, "WFValue": val,
    }

def wf_text(val):
    return {"Value": {"string": val}, "WFSerializationType": "WFTextTokenString"}

def wf_headers(items):
    return {"Value": {"WFDictionaryFieldValueItems": items}, "WFSerializationType": "WFDictionaryFieldValue"}

actions = [
    {"WFWorkflowActionIdentifier": "is.workflow.actions.comment", "WFWorkflowActionParameters": {
        "UUID": U_CMT1, "WFCommentActionText": "Shortcuts generated by Shortcuts Playground.\nisayscribe — Speak, get a formatted note."}},
    {"WFWorkflowActionIdentifier": "is.workflow.actions.comment", "WFWorkflowActionParameters": {
        "UUID": U_CMT2, "WFCommentActionText": "Shortcuts generated by Shortcuts Playground.\nEdit the Text action below: replace Bearer gsk_YOUR_KEY with your actual Groq key."}},
    # API key
    {"WFWorkflowActionIdentifier": "is.workflow.actions.gettext", "WFWorkflowActionParameters": {
        "UUID": U_KEY, "WFTextActionText": "Bearer gsk_YOUR_KEY"}},
    {"WFWorkflowActionIdentifier": "is.workflow.actions.comment", "WFWorkflowActionParameters": {
        "UUID": uid(), "WFCommentActionText": "Wiring: Dictate → JSON Text → Replace __T__ with dictation → Llama API → Create Note."}},
    # JSON template text
    {"WFWorkflowActionIdentifier": "is.workflow.actions.gettext", "WFWorkflowActionParameters": {
        "UUID": U_JSON, "WFTextActionText": JSON_BODY}},
    # Replace Text: swap __T__ with Dictated Text
    {"WFWorkflowActionIdentifier": "is.workflow.actions.text.replace", "WFWorkflowActionParameters": {
        "UUID": U_RPL,
        "WFInput": tts_attach(U_JSON, "Text"),
        "WFReplaceTextFind": "__T__",
        "WFReplaceTextReplace": tts_attach(U_DICT, "Dictated Text"),
    }},
    # Download URL (File body)
    {"WFWorkflowActionIdentifier": "is.workflow.actions.downloadurl", "WFWorkflowActionParameters": {
        "UUID": U_DL,
        "WFURL": "https://api.groq.com/openai/v1/chat/completions",
        "WFHTTPMethod": "POST",
        "WFHTTPBodyType": "File",
        "WFHTTPHeaders": wf_headers([
            wf_kv("Authorization", {"Value": {"OutputUUID": U_KEY, "OutputName": "Text", "Type": "ActionOutput"}, "WFSerializationType": "WFTextTokenAttachment"}),
            wf_kv("Content-Type", wf_text("application/json")),
        ]),
        "WFRequestVariable": {
            "Value": {"OutputUUID": U_RPL, "OutputName": "Updated Text", "Type": "ActionOutput"},
            "WFSerializationType": "WFTextTokenAttachment",
        },
        "ShowHeaders": True, "Advanced": True,
        "WFAllowsCellularAccess": 1, "WFAllowsRedirects": 1, "WFIgnoreCookies": 0, "WFTimeout": 120,
    }},
    # Get choices.1.message.content
    {"WFWorkflowActionIdentifier": "is.workflow.actions.getvalueforkey", "WFWorkflowActionParameters": {
        "UUID": U_GET, "WFDictionaryKey": "choices.1.message.content", "WFGetDictionaryValueType": "Value",
        "WFInput": tta_attach(U_DL, "Contents of URL"),
    }},
    # Create Note
    {"WFWorkflowActionIdentifier": "com.apple.mobilenotes.SharingExtension", "WFWorkflowActionParameters": {
        "UUID": U_NOTE, "AppIntentDescriptor": {"AppIntentIdentifier": "com.apple.mobilenotes.SharingExtension"},
        "name": "isayscribe - New Idea",
        "content": tta_attach(U_GET, "Dictionary Value"),
    }},
]

workflow = {
    "WFWorkflowActions": actions,
    "WFWorkflowClientVersion": "710", "WFWorkflowClientRelease": "2.1",
    "WFWorkflowIcon": {"WFWorkflowIconGlyphNumber": 61440, "WFWorkflowIconStartColor": 4282601983},
    "WFWorkflowImportQuestions": [],
    "WFWorkflowMinimumClientVersion": 900,
    "WFWorkflowName": "isayscribe",
    "WFWorkflowTypes": ["NCWidget", "WatchKit", "ActionExtension"],
}

out_path = os.path.join(BASE, "isayscribe.shortcut")
with open(out_path, "wb") as f:
    plistlib.dump(workflow, f, fmt=plistlib.FMT_XML)
subprocess.run(["plutil", "-convert", "binary1", out_path, "-o", out_path], check=True)
print("Built v3.4")
