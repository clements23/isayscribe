#!/usr/bin/env python3
"""isayscribe v3.3 — Dictate Text → Llama → Create Note. API key stored as Text action."""
import plistlib, uuid, os, subprocess

BASE = "/Users/clementsemerson/isayscribe"

with open(os.path.join(BASE, "prompt.txt"), "r", encoding="utf-8") as f:
    SYSTEM_PROMPT = f.read()

def uid():
    return str(uuid.uuid4()).upper()

U_CMT  = uid()
U_KEY  = uid()    # Text action: "Bearer YOUR_GROQ_API_KEY_HERE"
U_DICT = uid()    # Dictate Text
U_LLAMA = uid()   # Llama downloadurl
U_CHOICE = uid()  # getvalueforkey
U_NOTE  = uid()   # Create Note

def tok_attach(out_uuid, out_name):
    return {
        "Value": {"OutputUUID": out_uuid, "OutputName": out_name, "Type": "ActionOutput"},
        "WFSerializationType": "WFTextTokenAttachment",
    }

def wf_kv(key, item_type, value):
    return {"UUID": uid(), "WFKey": {"Value": {"string": key}, "WFSerializationType": "WFTextTokenString"}, "WFItemType": item_type, "WFValue": value}

def wf_text(val):
    return {"Value": {"string": val}, "WFSerializationType": "WFTextTokenString"}

def wf_dict_val(items):
    return {"Value": {"WFDictionaryFieldValueItems": items}, "WFSerializationType": "WFDictionaryFieldValue"}

actions = [
    # Comment 0: prompt block (required by validator)
    {"WFWorkflowActionIdentifier": "is.workflow.actions.comment", "WFWorkflowActionParameters": {
        "UUID": uid(), "WFCommentActionText": "Shortcuts generated by Shortcuts Playground.\nisayscribe — Speak your idea, get a formatted note."}},
    # Comment 1: instructions for API key
    {"WFWorkflowActionIdentifier": "is.workflow.actions.comment", "WFWorkflowActionParameters": {
        "UUID": uid(), "WFCommentActionText": "Shortcuts generated by Shortcuts Playground.\nEdit the Text action below: replace YOUR_GROQ_API_KEY_HERE with your Groq key (starts with gsk_). Keep 'Bearer ' at start."}},
    # Text: API key
    {"WFWorkflowActionIdentifier": "is.workflow.actions.gettext", "WFWorkflowActionParameters": {
        "UUID": U_KEY, "WFTextActionText": "Bearer YOUR_GROQ_API_KEY_HERE"}},
    # Dictate Text
    {"WFWorkflowActionIdentifier": "is.workflow.actions.dictatetext", "WFWorkflowActionParameters": {"UUID": U_DICT}},
    # Llama-3.3 chat completions
    {"WFWorkflowActionIdentifier": "is.workflow.actions.downloadurl", "WFWorkflowActionParameters": {
        "UUID": U_LLAMA,
        "WFURL": "https://api.groq.com/openai/v1/chat/completions",
        "WFHTTPMethod": "POST",
        "WFHTTPBodyType": "JSON",
        "WFHTTPHeaders": wf_dict_val([
            wf_kv("Authorization", 0, {
                "Value": {"OutputUUID": U_KEY, "OutputName": "Text", "Type": "ActionOutput"},
                "WFSerializationType": "WFTextTokenAttachment",
            }),
            wf_kv("Content-Type", 0, wf_text("application/json")),
        ]),
        "WFJSONValues": wf_dict_val([
            wf_kv("model", 0, wf_text("llama-3.3-70b-versatile")),
            wf_kv("messages", 2, {"Value": [
                {"WFItemType": 1, "WFValue": wf_dict_val([
                    wf_kv("role", 0, wf_text("system")),
                    wf_kv("content", 0, wf_text(SYSTEM_PROMPT)),
                ])},
                {"WFItemType": 1, "WFValue": wf_dict_val([
                    wf_kv("role", 0, wf_text("user")),
                    wf_kv("content", 0, {
                        "Value": {"OutputUUID": U_DICT, "OutputName": "Dictated Text", "Type": "ActionOutput"},
                        "WFSerializationType": "WFTextTokenAttachment",
                    }),
                ])},
            ], "WFSerializationType": "WFArrayParameterState"}),
        ]),
        "ShowHeaders": True, "Advanced": True,
        "WFAllowsCellularAccess": 1, "WFAllowsRedirects": 1, "WFIgnoreCookies": 0, "WFTimeout": 120,
    }},
    # Get Dictionary Value
    {"WFWorkflowActionIdentifier": "is.workflow.actions.getvalueforkey", "WFWorkflowActionParameters": {
        "UUID": U_CHOICE, "WFDictionaryKey": "choices.1.message.content", "WFGetDictionaryValueType": "Value",
        "WFInput": tok_attach(U_LLAMA, "Contents of URL"),
    }},
    # Create Note
    {"WFWorkflowActionIdentifier": "com.apple.mobilenotes.SharingExtension", "WFWorkflowActionParameters": {
        "UUID": U_NOTE, "AppIntentDescriptor": {"AppIntentIdentifier": "com.apple.mobilenotes.SharingExtension"},
        "name": "isayscribe - New Idea",
        "content": tok_attach(U_CHOICE, "Dictionary Value"),
    }},
]

workflow = {
    "WFWorkflowActions": actions,
    "WFWorkflowClientVersion": "710", "WFWorkflowClientRelease": "2.1",
    "WFWorkflowIcon": {"WFWorkflowIconGlyphNumber": 61440, "WFWorkflowIconStartColor": 4282601983},
    "WFWorkflowImportQuestions": [],
    "WFWorkflowMinimumClientVersion": 900,
    "WFWorkflowName": "isayscribe",
    "WFWorkflowTypes": ["NCWidget", "WatchKit", "ActionExtension"],
}

out_path = os.path.join(BASE, "isayscribe.shortcut")
with open(out_path, "wb") as f:
    plistlib.dump(workflow, f, fmt=plistlib.FMT_XML)
subprocess.run(["plutil", "-convert", "binary1", out_path, "-o", out_path], check=True)
print("Built. No import questions — edit the Text action inside the shortcut to set your Groq key.")
